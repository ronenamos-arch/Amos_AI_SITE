// Build-time generator: reads content/posts/*.md and writes
// lib/generated/posts-index.ts as a static TypeScript module.
//
// Why this exists: Next.js node-file-trace cannot statically analyze
// fs.readdirSync(process.cwd()) calls, so posts added after a cached
// build would not be bundled into the serverless function, causing 404s.
// A static .ts module is guaranteed to be bundled because it's a real
// import dependency.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const postsDir = path.join(root, "content", "posts");
const outDir = path.join(root, "lib", "generated");
const outFile = path.join(outDir, "posts-index.ts");

fs.mkdirSync(outDir, { recursive: true });

const files = fs.existsSync(postsDir)
  ? fs.readdirSync(postsDir).filter((f) => {
      const lower = f.toLowerCase();
      return lower.endsWith(".md") || lower.endsWith(".mdx");
    })
  : [];

const entries = files.map((filename) => {
  const slug = filename.replace(/\.mdx?$/i, "");
  const raw = fs.readFileSync(path.join(postsDir, filename), "utf-8");
  return { slug, raw };
});

const header = `// AUTO-GENERATED by scripts/generate-posts-index.mjs — DO NOT EDIT BY HAND.
// Regenerated on every build from content/posts/*.md so posts are statically
// bundled into the serverless function (node-file-trace can't see dynamic fs reads).
`;

const body = `export const POSTS_INDEX: ReadonlyArray<{ slug: string; raw: string }> = ${JSON.stringify(entries, null, 2)};\n`;

fs.writeFileSync(outFile, header + "\n" + body, "utf-8");
console.log(`[generate-posts-index] wrote ${entries.length} posts → ${path.relative(root, outFile)}`);
